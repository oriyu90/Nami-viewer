let currentLang = 'ja';
const warned = new Set();

export function setLang(lang) {
  currentLang = lang === 'en' ? 'en' : 'ja';
  if (typeof document !== 'undefined') {
    document.documentElement.lang = currentLang;
  }
  return currentLang;
}

export function getLang() {
  return currentLang;
}

export function hasKey(key) {
  return Object.prototype.hasOwnProperty.call(dictionaries[currentLang], key)
    || Object.prototype.hasOwnProperty.call(dictionaries.en, key);
}

export function interpolate(template, params) {
  if (!params || typeof template !== 'string') return template;
  return template.replace(/\{([A-Za-z0-9_]+)\}/g, (match, name) => {
    if (Object.prototype.hasOwnProperty.call(params, name)) {
      const value = params[name];
      return value == null ? '' : String(value);
    }
    return match;
  });
}

export function t(key, params = {}) {
  const active = dictionaries[currentLang] || dictionaries.en;
  let text = active[key];
  if (text == null) text = dictionaries.en[key];
  if (text == null) {
    if (!warned.has(key) && typeof console !== 'undefined') {
      warned.add(key);
      console.warn(`[i18n] missing key: ${key}`);
    }
    return key;
  }
  return interpolate(text, params);
}

export function formatNumber(value, options = {}) {
  const n = Number(value);
  if (!Number.isFinite(n)) return '—';
  try {
    return new Intl.NumberFormat(currentLang === 'ja' ? 'ja-JP' : 'en-US', options).format(n);
  } catch {
    return String(n);
  }
}

export function applyI18n(root) {
  if (typeof document === 'undefined') return;
  const scope = root || document;
  const nodes = [];
  if (scope.nodeType === 1 && scope.matches && scope.matches('[data-i18n]')) nodes.push(scope);
  if (scope.querySelectorAll) {
    nodes.push(...scope.querySelectorAll('[data-i18n]'));
  }
  for (const el of nodes) {
    const key = el.getAttribute('data-i18n');
    if (key) el.textContent = t(key);
  }
  const each = (selector, attr, apply) => {
    const list = [];
    if (scope.nodeType === 1 && scope.matches && scope.matches(selector)) list.push(scope);
    if (scope.querySelectorAll) list.push(...scope.querySelectorAll(selector));
    for (const el of list) {
      const key = el.getAttribute(attr);
      if (key) apply(el, t(key));
    }
  };
  each('[data-i18n-title]', 'data-i18n-title', (el, text) => { el.title = text; });
  each('[data-i18n-aria]', 'data-i18n-aria', (el, text) => { el.setAttribute('aria-label', text); });
  each('[data-i18n-placeholder]', 'data-i18n-placeholder', (el, text) => { el.placeholder = text; });
  if (scope === document) {
    document.title = t('app.title');
  }
}

export function flattenKeys(lang) {
  const dict = dictionaries[lang];
  return dict ? Object.keys(dict).sort() : [];
}

